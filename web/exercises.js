/* =====================================================================
   ТОННАЖ — база движений
   ---------------------------------------------------------------------
   Каждое упражнение привязано к ДВИГАТЕЛЬНОМУ ПАТТЕРНУ (pattern).
   Движок программы оперирует паттернами, а не конкретными названиями:
   «в этот слот нужна горизонтальная тяга» — а какую именно поставить,
   решает ротация. Отсюда берётся разнообразие без потери прогрессии.

   tier:
     'anchor' — базовое движение блока. Держится 2 мезоцикла подряд,
                потому что прогресс в весах требует повторяемости.
     'rotate' — подсобка. Меняется каждый мезоцикл.
   unit:
     'kg'     — обычный вес снаряда
     'time'   — удержание в секундах
     'bw'     — собственный вес (записываем только повторы)
     'assist' — противовес тренажёра (меньше = тяжелее)
   step:      шаг прибавки веса в кг при выполненной двойной прогрессии
   level:     1 — можно с первого дня, 2 — нужен базовый навык, 3 — сложное
   ===================================================================== */

