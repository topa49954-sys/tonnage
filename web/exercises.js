/* Все упражнения одного паттерна, отсортированные по уровню сложности */
export function byPattern(pattern) {
  return Object.entries(EX)
    .filter(([, e]) => e.pattern === pattern)
    .sort((a, b) => a[1].level - b[1].level)
    .map(([id]) => id);
}

